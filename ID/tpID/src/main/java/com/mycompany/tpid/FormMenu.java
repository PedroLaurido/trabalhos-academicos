        try {
            String continente = txtPaisesContinenteNome_Valor.getText(); // Obtém o continente fornecido pelo usuário
            String valorMinPopulacao = txtPaisesContinenteMinPop_Valor.getText(); // Obtém o valor mínimo de população fornecido pelo usuário

            // XPath para encontrar os países do continente com população igual ou superior ao valor mínimo
            String xpPaisesMinPopulacao = "//factos[contains(continente, '" + continente + "') and xs:integer(populacao) >= " + valorMinPopulacao + "]/@nome";
            XdmValue resPaisesMinPopulacao = XPathFunctions.executaXpath(xpPaisesMinPopulacao, "factos.xml");

            // Lista de países que atendem aos critérios
            ArrayList<String> paisesEncontrados = new ArrayList<>();
            for (XdmItem item : resPaisesMinPopulacao) {
                paisesEncontrados.add(item.getStringValue());
            }

            // Verifica se foram encontrados países que atendem aos critérios
            if (paisesEncontrados.isEmpty()) {
                JOptionPane.showMessageDialog(this,
                        "Sem resultados para os países do continente " + continente + " com uma população maior ou igual a " + valorMinPopulacao,
                        "Aviso",
                        JOptionPane.ERROR_MESSAGE);
            } else {
                // Concatena os nomes dos países encontrados em uma única string
                StringBuilder sb = new StringBuilder();
                for (String pais : paisesEncontrados) {
                    sb.append(pais).append("\n");
                }
                txtPaisesContinenteMinPop.setText(sb.toString().trim());
            }
        } catch (SaxonApiException ex) {
            Logger.getLogger(FormMenu.class.getName()).log(Level.SEVERE, null, ex);
        }


